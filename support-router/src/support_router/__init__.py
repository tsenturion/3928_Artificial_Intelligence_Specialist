"""Учебный проект: от текстового классификатора до выпуска контейнера.

Задача приложения — отнести обращение к одному из четырёх направлений поддержки.
Набор синтетический: результаты на нём показывают работу процесса разработки,
а качество для реальных клиентов нужно отдельно проверять на реальных данных.

Порядок чтения исходников:
    params.toml и config.py — настройки и пути одного запуска;
    data.py — проверка CSV, очистка, фиксированные train/test и защита от утечки;
    model.py — обучение Pipeline, сохранение модели вместе с метаданными;
    evaluate.py и release.py — контроль качества и разрешение выпуска;
    cli.py — вызов этих операций из командной строки;
    schemas.py и api.py — контракт FastAPI, загрузка модели и HTTP-запросы;
    text_profile.py и monitoring.py — профиль обучающих данных и наблюдение в работе.

Инфраструктура находится рядом с Python-пакетом:
    dvc.yaml описывает зависимости prepare → train → evaluate;
    dvc.lock связывает выбранные входы с результатами конкретного запуска;
    Dockerfile упаковывает готовую модель и приложение;
    compose.yaml собирает локальный образ, compose.release.yaml запускает готовый;
    .github/workflows/support-router.yml в корне репозитория выполняет CI/CD.

Команды из папки support-router после установки Python и зависимостей:
    python -m pip install -e ".[dev,mlops]"
    python -m support_router run
    python -m support_router verify
    python -m support_router predict "Курьер не привёз заказ"

Для работы с версиями данных и моделей используйте Управление_DVC.ps1.
Первичная настройка и восстановление данных описаны в комментариях этого скрипта.
Запустить_приложение.ps1 собирает интерфейс и поднимает FastAPI.
Запустить_Docker.ps1 собирает контейнер локально, а Обновить_приложение.ps1
загружает уже проверенный образ GHCR. Скрипты запускаются в PowerShell 7.

Исходные данные, подготовленные выборки, модель и отчёты не включаются в Git:
ими управляет DVC. Git хранит код, параметры, указатели и описание процесса.
Журналы и SQLite мониторинга находятся в logs; порог очистки составляет 30 дней.
В контейнере этот каталог подключён как volume и переживает замену контейнера.
Очистка просроченных SQLite-записей выполняется при запуске и обращении к хранилищу.
Эта справка доступна также через help(support_router) в Python.
"""

